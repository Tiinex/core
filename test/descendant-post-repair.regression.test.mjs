import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {projectPortableEditorAssistance} from '../src/tooling/portable/editor/editor.assistance.js';
import {canonicalC14nV2SelfState} from '../src/integrity/integrity.c14nV2.js';
const root=path.resolve(process.env.TIINEX_TEST_BUSINESS_ROOT || '../business');
const dir=path.join(root,'.topics','initiatives');
const names=['001-initiatives.trace.md','001-2-public-trust-contribution-governance-task.trace.md','001-2-1-public-challenge-closure-and-bounty-decision-task.trace.md'];
const records=names.map(name=>({path:'.topics/initiatives/'+name,markdown:fs.readFileSync(path.join(dir,name),'utf8')}));
const focus=records[1].path;
const projection=(records,includeDescendantRepair=true)=>projectPortableEditorAssistance({records,focusPath:focus,includeDescendantRepair}).documents[0];
test('independently repaired Parent has a separately qualified optional descendant-only changeset',()=>{
 const source=records[1];
 const before=projectPortableEditorAssistance({records,focusPath:focus,selectedParentPath:records[0].path}).documents[0];
 const selected=before.actions.find(x=>x.id==='relocate-selected-parent-and-self-seal');
 assert.ok(selected,'operator Parent fix is qualified');
 assert.equal(selected.descendantCount,1,'one known descendant in this Workspace');
 const revised=[records[0],{...source,markdown:selected.replacementMarkdown},records[2]];
 const ordinary=projection(revised,false);
 assert.equal(ordinary.actions.some(x=>x.id==='refresh-descendant-integrity'),false,'ordinary diagnostics must not discover expensive cascade');
 const after=projection(revised);
 const cascade=after.actions.find(x=>x.id==='refresh-descendant-integrity');
 assert.ok(cascade,'Core offers a separate descendants-only follow-up after Parent edit');
 assert.equal(cascade.kind,'replace-record-set');
 assert.equal(cascade.replacements.length,1);
 assert.equal(cascade.replacements[0].path,records[2].path);
 assert.equal(cascade.sourceSha256.length,64);
 assert.equal(canonicalC14nV2SelfState(cascade.replacements[0].replacementMarkdown).state,'verified');
 assert.equal(revised[2].markdown,records[2].markdown,'projection must not mutate child');
 const resolved=revised.map(r=>r.path===records[2].path?{...r,markdown:cascade.replacements[0].replacementMarkdown}:r);
 assert.equal(projection(resolved).actions.some(x=>x.id==='refresh-descendant-integrity'),false,'no prompt when children already match');
});
test('unavailable descendant blocks all-or-nothing cascade',()=>{
 const selected=projectPortableEditorAssistance({records,focusPath:focus,selectedParentPath:records[0].path}).documents[0].actions.find(x=>x.id==='relocate-selected-parent-and-self-seal');
 assert.ok(selected);
 const corrupted=records[2].markdown.replace(/  - Trace: \[Public Trust, Contribution And Governance Surface\]\([^)]*\)/,'  - Trace: [Unknown](missing.trace.md)');
 const result=projection([records[0],{...records[1],markdown:selected.replacementMarkdown},{...records[2],markdown:corrupted}]);
 assert.equal(result.actions.some(a=>a.id==='refresh-descendant-integrity'),false,'never infer an ambiguous child Parent');
});
