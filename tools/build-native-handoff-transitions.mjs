/** Native Handoff Transition material compilation. Artifact Markdown remains the only authored source. */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'src/schemas/coordination/handoff');
const output = join(root, 'src/tooling/portable/transitions/native.handoff.generated.js');
const entries = [];
for (const name of ['handoff-semantic-package.trace.md', 'tiinex.handoff.v1-transitions.trace.md']) {
  entries.push([`coordination/handoff/${name}`, await readFile(join(source, name), 'utf8')]);
}
for (const name of (await readdir(join(source, '.transitions'))).filter((name) => name.endsWith('.trace.md')).sort()) {
  entries.push([`coordination/handoff/.transitions/${name}`, await readFile(join(source, '.transitions', name), 'utf8')]);
}
if (entries.length !== 8) throw new Error(`native.handoff.material-count.unexpected:${entries.length}`);
const expected = '// Generated by tools/build-native-handoff-transitions.mjs; authored sources: src/schemas/coordination/handoff.\n'
  + `export const nativeHandoffTransitionMarkdown = Object.freeze(${JSON.stringify(entries, null, 2)});\n`;
if (process.argv.includes('--check')) {
  const actual = await readFile(output, 'utf8').catch(() => '');
  if (actual !== expected) throw new Error('native.handoff.generated.stale');
  console.log('Native Handoff source / projection: byte-consistent');
} else {
  await writeFile(output, expected);
  console.log('Compiled native Handoff Transition material');
}
