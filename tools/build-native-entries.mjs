/** Native Entry material compilation. Artifact Markdown remains the only authored Entry source. */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const valueAfter = (flag) => {
  const index = argv.indexOf(flag);
  return index >= 0 ? String(argv[index + 1] || '').trim() : '';
};
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'src/schemas/entry/.entries');
const output = join(root, 'src/tooling/portable/entry/native.entry.generated.js');
const schemaOutput = join(root, 'src/tooling/portable/entry/native.entry.schema.generated.js');
const names = (await readdir(source)).filter((name) => name.endsWith('.trace.md')).sort();
const entries = [];
for (const name of names) entries.push([`entry/.entries/${name}`, await readFile(join(source, name), 'utf8')]);
if (entries.length < 1) throw new Error('native.entry.materials.missing');
const expected = '// Generated by tools/build-native-entries.mjs; authored sources: src/schemas/entry/.entries.\n'
  + `export const nativeEntryMarkdown = Object.freeze(${JSON.stringify(entries, null, 2)});\n`;

let schemaExpected = '';
const docsArg = valueAfter('--docs');
if (docsArg) {
  const docsRoot = resolve(process.cwd(), docsArg);
  const schemaRoot = join(docsRoot, '.topics/.schemas/entry');
  const schemaFiles = await walkSchemaFiles(schemaRoot);
  if (!schemaFiles.length) throw new Error('native.entry.schemas.missing');
  const commit = valueAfter('--docs-commit');
  if (commit && !/^[0-9a-f]{40}$/i.test(commit)) throw new Error('native.entry.docs-commit.invalid');
  const markdownById = {};
  const sourceById = {};
  for (const absolutePath of schemaFiles) {
    const schemaMarkdown = await readFile(absolutePath, 'utf8');
    const schemaId = currentSchemaId(schemaMarkdown);
    if (!schemaId) throw new Error(`native.entry.schema-id.missing:${relative(schemaRoot, absolutePath)}`);
    if (markdownById[schemaId]) throw new Error(`native.entry.schema-id.duplicate:${schemaId}`);
    const sourcePath = relative(docsRoot, absolutePath).replace(/\\/g, '/');
    markdownById[schemaId] = schemaMarkdown;
    sourceById[schemaId] = {
      provider: 'docs-workspace',
      repository: 'Tiinex/docs',
      commit,
      publicationState: commit ? 'published-immutable-canonical' : 'qualified-local-unpublished',
      sourcePath
    };
  }
  if (!markdownById['tiinex.entry.v1']) throw new Error('native.entry.base-schema.missing');
  schemaExpected = '// Generated by tools/build-native-entries.mjs from Tiinex/docs .topics/.schemas/entry schema family.\n'
    + `export const nativeEntrySchemaMarkdownById = Object.freeze(${JSON.stringify(markdownById, null, 2)});\n`
    + `export const nativeEntrySchemaSourceById = Object.freeze(${JSON.stringify(sourceById, null, 2)});\n`
    + `export function nativeEntrySchemaMarkdownForId(schemaId = '') { return nativeEntrySchemaMarkdownById[String(schemaId || '')] || ''; }\n`
    + `export const nativeEntrySchemaMarkdown = nativeEntrySchemaMarkdownById['tiinex.entry.v1'];\n`
    + `export const nativeEntrySchemaSource = nativeEntrySchemaSourceById['tiinex.entry.v1'];\n`;
}

if (check) {
  const actual = await readFile(output, 'utf8').catch(() => '');
  if (actual !== expected) throw new Error('native.entry.generated.stale');
  if (schemaExpected) {
    const schemaActual = await readFile(schemaOutput, 'utf8').catch(() => '');
    if (schemaActual !== schemaExpected) throw new Error('native.entry.schema.generated.stale');
  }
  console.log(schemaExpected ? 'Native Entry sources / Entry schema family projection: byte-consistent' : 'Native Entry source / projection: byte-consistent');
} else {
  await writeFile(output, expected);
  if (schemaExpected) await writeFile(schemaOutput, schemaExpected);
  console.log(schemaExpected ? 'Compiled native Entry material and Entry schema family projection' : 'Compiled native Entry material');
}

async function walkSchemaFiles(dir) {
  const out = [];
  for (const item of await readdir(dir, { withFileTypes: true })) {
    const absolute = join(dir, item.name);
    if (item.isDirectory()) out.push(...await walkSchemaFiles(absolute));
    else if (item.isFile() && item.name.endsWith('.schema.md')) out.push(absolute);
  }
  return out.sort((a, b) => a.localeCompare(b));
}

function currentSchemaId(markdown = '') {
  const match = String(markdown || '').match(/^\s*-\s+Current Schema:\s+(?:\[[^\]]+\]\(([^)]+)\)|([^\s]+))\s*$/m);
  const raw = String(match?.[1] || match?.[2] || '').trim();
  if (!raw) return '';
  const file = raw.split('/').pop() || raw;
  return file.replace(/\.schema\.md$/i, '').trim();
}
